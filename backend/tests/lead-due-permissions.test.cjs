const assert = require('node:assert/strict');
process.env.DATABASE_URL ||= 'postgresql://unused/test';
const { getScheduleDateRanges, buildFollowUpDueClause, leadRepository } = require('../dist/features/leads/lead.repository');
const { employeeLeadPermissions } = require('../dist/constants/permissions');
const { LeadModel } = require('../dist/models/Lead.model');
require('../dist/utils/activityLogger').logActivity = async () => {};
const { leadService } = require('../dist/features/leads/lead.service');
const now = new Date('2026-10-13T20:00:00Z');
const ranges = getScheduleDateRanges(now);
assert.equal(ranges.startOfDay.toISOString(), '2026-10-13T18:30:00.000Z');
assert.equal(ranges.tomorrowStart.toISOString(), '2026-10-14T18:30:00.000Z');
const overdue = buildFollowUpDueClause('overdue', now);
assert.equal(overdue.nextFollowUpDate.$ne, null);
assert.equal(overdue.nextFollowUpDate.$exists, true);
assert.ok(overdue.status.$in.includes('hold'));
assert.ok(!overdue.status.$in.includes('closed'));
assert.ok(employeeLeadPermissions('employee', []).includes('lead:create'));
assert.ok(employeeLeadPermissions('employee', []).includes('lead:status:update'));
assert.deepEqual(employeeLeadPermissions('custom', []), []);
const employee = {userId:'111111111111111111111111', permissions:['lead:read_assigned', 'lead:status:update']};
const lead = {_id:'333333333333333333333333', assignedTo:employee.userId, status:'open'};
let cleared = false;
leadRepository.findById = async () => lead;
leadRepository.update = async (id, data) => ({...lead, ...data});
leadRepository.syncNextFollowUpDate = async () => {cleared = true;};
leadRepository.createActivity = async () => ({});
(async () => {
  LeadModel.countDocuments = async query => {assert.deepEqual(query.nextFollowUpDate, overdue.nextFollowUpDate); return 1;};
  assert.equal(await leadRepository.countFollowUpsDue({}, now, 'overdue'), 1);
  const result = await leadService.updateStatus(lead._id, {status:'closed'}, employee);
  assert.equal(result.status, 'closed');
  assert.ok(cleared);
  await assert.rejects(() => leadService.updateStatus(lead._id, {status:'closed'}, {...employee,userId:'222222222222222222222222'}), /permission/);
  console.log('Passed: India day boundaries, missing-date exclusion, active status scope, employee permissions and assigned lead closing');
})().catch(error => {console.error(error);process.exitCode=1;});
